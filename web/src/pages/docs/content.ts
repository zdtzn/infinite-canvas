export function searchGuideSections(query: string, sections = guideSections) {
    const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
    if (!terms.length) return sections;

    return sections.filter((section) => {
        const searchable = [section.label, section.title, section.summary, ...section.keywords, ...section.blocks.flatMap((block) => [block.title, block.note || "", ...block.items])].join(" ").toLocaleLowerCase();
        return terms.every((term) => searchable.includes(term));
    });
}
